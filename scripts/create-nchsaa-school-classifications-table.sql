CREATE TABLE IF NOT EXISTS nchsaa_school_classifications (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    school_name TEXT NOT NULL,
    division TEXT NOT NULL,
    enrollment INTEGER,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Create index for faster lookups
CREATE INDEX IF NOT EXISTS idx_nchsaa_school_name ON nchsaa_school_classifications(school_name);
CREATE INDEX IF NOT EXISTS idx_nchsaa_division ON nchsaa_school_classifications(division);

