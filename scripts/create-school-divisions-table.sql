  id SERIAL PRIMARY KEY,
  school_name VARCHAR(255) NOT NULL,
  division VARCHAR(2) NOT NULL,
  enrollment INTEGER,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

