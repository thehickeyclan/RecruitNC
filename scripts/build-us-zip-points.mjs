// Builds lib/recruiting/us-zip-points.ts from the US Census Bureau ZCTA Gazetteer
// (https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip).
// Usage: node scripts/build-us-zip-points.mjs /path/to/2024_Gaz_zcta_national.txt
import { readFileSync, writeFileSync } from "node:fs"

const src = process.argv[2]
if (!src) throw new Error("Pass the path to the unzipped 2024_Gaz_zcta_national.txt")
const [header, ...rows] = readFileSync(src, "utf8").trim().split(/\r?\n/)
const cols = header.split("\t").map((c) => c.trim())
const zi = cols.indexOf("GEOID"), la = cols.indexOf("INTPTLAT"), lo = cols.indexOf("INTPTLONG")
const out = []
for (const row of rows) {
  const f = row.split("\t").map((c) => c.trim())
  const lat = Number(f[la]), lon = Number(f[lo])
  if (!/^\d{5}$/.test(f[zi]) || !Number.isFinite(lat) || !Number.isFinite(lon)) throw new Error(`Bad row: ${row}`)
  out.push(`${f[zi]}${lat.toFixed(2)},${lon.toFixed(2)}`)
}
out.sort()
writeFileSync(
  "lib/recruiting/us-zip-points.ts",
  `// GENERATED by scripts/build-us-zip-points.mjs. Do not edit by hand.\n` +
    `// US Census Bureau 2024 ZCTA Gazetteer: the internal point of every US ZIP code area (${out.length} ZIPs), to 0.01 degrees (about 1 km).\n` +
    `// Format: ";"-separated records of ZIP (5 digits) then "lat,lon".\n` +
    `export const US_ZIP_POINTS_SOURCE = "US Census Bureau 2024 ZCTA Gazetteer"\n` +
    `export const US_ZIP_POINTS = "${out.join(";")}"\n`,
)
console.log(`${out.length} ZIPs written`)
