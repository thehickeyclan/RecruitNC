/**
 * Reads official NCHSAA tournament JSON and writes SQL for wrestling_nchsaa_results.
 *
 * Expected JSON shape (top-level):
 *   {
 *     "tournament": "optional label",
 *     "classifications": [
 *       {
 *         "classification": "7A",
 *         "weight_classes": [
 *           {
 *             "weight": 165,
 *             "places": [
 *               { "place": 1, "name": "First Last", "school": "School Name" },
 *               ...
 *             ]
 *           }
 *         ]
 *       }
 *     ]
 *   }
 *
 * Usage:
 *   node scripts/import-nchsaa-2026-placers-from-json.js path/to/nchsaa-2026.json
 *   node scripts/import-nchsaa-2026-placers-from-json.js   # defaults to scripts/nchsaa-2026-state-placers.json
 *
 * Output: scripts/generated-nchsaa-2026-placers-insert.sql
 *
 * Before running SQL in Supabase:
 *   1) Export or backup rows you might need: SELECT * FROM wrestling_nchsaa_results WHERE year = 2026;
 *   2) Review the generated file; uncomment DELETE only if you intend to replace all 2026 placers (1–4).
 *   3) Run in SQL Editor on the same project as Vercel SUPABASE_URL (Legacy/RecruitNC).
 *
 * Notes:
 *   - Does not touch place = 0 (state qualifiers) unless you run a separate DELETE.
 *   - Men’s and women’s both use the same columns; classification strings differ (e.g. 7A vs 1-4A).
 *   - If you get unique-constraint errors, delete conflicting 2026 placers first (see DELETE block).
 */
const fs = require("fs");
const path = require("path");

const defaultIn = path.join(__dirname, "nchsaa-2026-state-placers.json");
const outPath = path.join(__dirname, "generated-nchsaa-2026-placers-insert.sql");

const inputPath = path.resolve(process.argv[2] || defaultIn);

function escapeSql(s) {
  return String(s ?? "").replace(/'/g, "''");
}

function sqlEsc(v) {
  if (typeof v === "number" && Number.isFinite(v)) return String(v);
  return `'${escapeSql(String(v))}'`;
}

function collectRows(data) {
  const year =
    typeof data.year === "number"
      ? data.year
      : typeof data.tournament_year === "number"
        ? data.tournament_year
        : 2026;

  const rows = [];
  const classifications = data.classifications || data.classification_results || [];

  for (const block of classifications) {
    const classification = block.classification ?? block.division ?? block.class;
    if (!classification) continue;

    const weightClasses = block.weight_classes || block.weights || [];
    for (const wc of weightClasses) {
      const w = wc.weight ?? wc.weight_class ?? wc.class;
      const weight_class = w == null ? "" : String(w).trim();
      if (!weight_class) continue;

      const places = wc.places || wc.results || [];
      for (const p of places) {
        const place = p.place ?? p.rank ?? p.finish;
        const name = (p.name ?? p.wrestler_name ?? "").trim();
        const school = (p.school ?? p.team ?? "").trim();
        if (place == null || name === "") continue;

        rows.push({
          year,
          classification: String(classification).trim(),
          weight_class,
          place: Number(place),
          wrestler_name: name,
          school,
        });
      }
    }
  }

  return rows;
}

function main() {
  if (!fs.existsSync(inputPath)) {
    console.error("Missing input file:", inputPath);
    console.error("Create it (copy from nchsaa-2026-state-placers.example.json) or pass a path as argv[2].");
    process.exit(1);
  }

  const raw = fs.readFileSync(inputPath, "utf8");
  let data;
  try {
    data = JSON.parse(raw);
  } catch (e) {
    console.error("Invalid JSON:", e.message);
    process.exit(1);
  }

  const rows = collectRows(data);
  if (rows.length === 0) {
    console.error("No rows parsed. Check JSON shape (classifications → weight_classes → places).");
    process.exit(1);
  }

  const badPlace = rows.filter((r) => r.place < 1 || r.place > 8);
  if (badPlace.length) {
    console.warn(
      "Warning: some rows have place outside 1–8 (will still be emitted):",
      badPlace.slice(0, 5)
    );
  }

  const values = rows
    .map(
      (r) =>
        `(${r.year}, ${sqlEsc(r.classification)}, ${sqlEsc(r.weight_class)}, ${r.place}, ${sqlEsc(r.wrestler_name)}, ${sqlEsc(r.school)})`
    )
    .join(",\n");

  const sql = `-- AUTO-GENERATED by scripts/import-nchsaa-2026-placers-from-json.js
-- Source: ${path.basename(inputPath)}
-- Rows: ${rows.length}
-- Table: wrestling_nchsaa_results
--
-- Run in Supabase SQL Editor (project tied to Vercel SUPABASE_URL).
--
-- 1) Optional: export current 2026 placers before replacing:
--    SELECT * FROM wrestling_nchsaa_results WHERE year = 2026 AND place BETWEEN 1 AND 4 ORDER BY classification, weight_class, place;
--
-- 2) Uncomment the block below ONLY if you want to remove existing 2026 *placer* rows (1–4)
--    and replace entirely with this file. This does NOT delete place = 0 (SQ) rows.
--
-- BEGIN;
-- DELETE FROM wrestling_nchsaa_results
-- WHERE year = 2026 AND place BETWEEN 1 AND 4;
-- COMMIT;

BEGIN;

INSERT INTO wrestling_nchsaa_results (year, classification, weight_class, place, wrestler_name, school)
VALUES
${values};

COMMIT;
`;

  fs.writeFileSync(outPath, sql, "utf8");
  console.log("Wrote", rows.length, "rows →", outPath);
}

main();
